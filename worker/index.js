/* ==========================================================================
   DELIVERY OS — Cloudflare Worker
   --------------------------------------------------------------------------
   やることはひとつだけ。サイト本体（静的アセット）を返す。

   静的アセットは既定でWorkerより先に返るので、ここに来るのは
   実在しないパスだけ。それは env.ASSETS がサイトの404へ回す。

   データベースも保存する情報も持たない。
   ========================================================================== */

export default {
  async fetch(request, env) {
    return env.ASSETS.fetch(request);
  }
};
